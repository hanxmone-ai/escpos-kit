"""Generates lib/src/gbk_table.dart from Python's built-in GBK codec.

Run from the repository root:  python3 tool/gen_gbk_table.py

Layout of the data (base64 in the Dart file):
  dense:  for U+4E00..U+9FA5, two bytes (lead, trail) per code point, in order.
  sparse: for every other BMP character that GBK can encode, four bytes:
          code point (big endian, 2 bytes), lead, trail. Sorted by code point.
"""

import base64
from pathlib import Path

DENSE_FIRST, DENSE_LAST = 0x4E00, 0x9FA5

dense = bytearray()
for cp in range(DENSE_FIRST, DENSE_LAST + 1):
    encoded = chr(cp).encode("gbk")
    assert len(encoded) == 2, hex(cp)
    dense += encoded

sparse = bytearray()
for cp in [*range(0x80, DENSE_FIRST), *range(DENSE_LAST + 1, 0x10000)]:
    if 0xD800 <= cp <= 0xDFFF:
        continue
    try:
        encoded = chr(cp).encode("gbk")
    except UnicodeEncodeError:
        continue
    assert len(encoded) == 2, hex(cp)
    sparse += cp.to_bytes(2, "big") + encoded


def dart_string(name: str, data: bytes) -> str:
    text = base64.b64encode(data).decode()
    lines = [text[i : i + 72] for i in range(0, len(text), 72)]
    body = "\n".join(f"    '{line}'" for line in lines)
    return f"const String {name} =\n{body};\n"


out = Path(__file__).resolve().parent.parent / "lib" / "src" / "gbk_table.dart"
out.write_text(
    "// GENERATED by tool/gen_gbk_table.py. Do not edit by hand.\n"
    "// GBK (CP936) encoding table; see that script for the layout.\n\n"
    f"const int gbkDenseFirst = 0x{DENSE_FIRST:04X};\n"
    f"const int gbkDenseLast = 0x{DENSE_LAST:04X};\n\n"
    + dart_string("gbkDenseBase64", bytes(dense))
    + "\n"
    + dart_string("gbkSparseBase64", bytes(sparse))
)
print(f"wrote {out} ({len(dense)} dense bytes, {len(sparse) // 4} sparse entries)")
